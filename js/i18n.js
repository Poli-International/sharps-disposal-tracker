window.APP_LANG = (function() {
  try {
    const saved = localStorage.getItem('poli_tools_language') || localStorage.getItem('poli-language');
    if (saved && window.I18N_STRINGS && window.I18N_STRINGS[saved]) return saved;
  } catch (e) {}
  if (typeof document !== 'undefined' && document.documentElement && document.documentElement.lang) {
    const docLang = document.documentElement.lang.slice(0, 2).toLowerCase();
    if (window.I18N_STRINGS && window.I18N_STRINGS[docLang]) return docLang;
  }
  return 'en';
})();

/**
 * Global translation function
 */
window.t = function(key, params = {}) {
  const lang = (window.APP_LANG || localStorage.getItem('poli_tools_language') || localStorage.getItem('poli-language') || (document.documentElement && document.documentElement.lang) || 'en').slice(0, 2).toLowerCase();
  const activeDict = window.I18N_STRINGS[lang] || window.I18N_STRINGS.en;
  const keys = key.split('.');
  
  let val = activeDict;
  for (const k of keys) {
    if (val && typeof val === 'object' && k in val) {
      val = val[k];
    } else {
      val = null;
      break;
    }
  }
  
  // Fallback to English if key missing in target language
  if (val === null || val === undefined) {
    let fallback = window.I18N_STRINGS.en;
    for (const k of keys) {
      if (fallback && typeof fallback === 'object' && k in fallback) {
        fallback = fallback[k];
      } else {
        return key;
      }
    }
    val = fallback;
  }

  if (typeof val === 'string') {
    return val.replace(/\{(\w+)\}/g, function(_, token) {
      return params[token] !== undefined ? params[token] : '{' + token + '}';
    });
  }
  return key;
};

/**
 * Set active language and trigger translation refresh
 */
window.setLanguage = function(lang) {
  if (!lang || !window.I18N_STRINGS || !window.I18N_STRINGS[lang]) {
    lang = 'en';
  }
  window.APP_LANG = lang;
  try {
    localStorage.setItem('poli_tools_language', lang);
    localStorage.setItem('poli-language', lang);
  } catch (e) {}
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = lang;
  }
  if (typeof window.applyDeclarativeTranslations === 'function') {
    window.applyDeclarativeTranslations();
  }
  if (typeof window.renderAll === 'function') {
    window.renderAll();
  }
};
